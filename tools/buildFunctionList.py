#!/usr/bin/env python3
"""Render doc/html/FunctionList.html from doc/functionlist.csv (stdlib only).

The CSV is the single authority for the catalogue (HANDOVER Part F, rule R1);
this page is a derived copy. auditPackage.py renders the same page in memory
and fails when the committed file differs, so staleness is decided by content
(HANDOVER O-11). The version and date in the footer come from
+NonGravForces/toolboxVersion.m, the single authority for the version.

Usage:  python tools/buildFunctionList.py            # writes the page
        python tools/buildFunctionList.py --check    # exit 1 if the page is stale
"""
import csv, html, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CSV = os.path.join(ROOT, "doc", "functionlist.csv")
OUT = os.path.join(ROOT, "doc", "html", "FunctionList.html")
VERSION_FILE = os.path.join(ROOT, "+NonGravForces", "toolboxVersion.m")

STYLE = ("body{font-family:Helvetica,Arial,sans-serif;max-width:900px;margin:2em auto;line-height:1.45}"
         "code,pre{background:#f4f4f4;padding:2px 4px}pre{padding:8px;overflow-x:auto}"
         "table{border-collapse:collapse}td,th{border:1px solid #ccc;padding:4px 8px;text-align:left}"
         "h1{border-bottom:2px solid #555}")


def read_version():
    """Version, date and model as toolboxVersion.m states them (numeric fields are the authority)."""
    src = open(VERSION_FILE, encoding="utf-8").read()
    m = re.search(r"major\s*=\s*uint16\((\d+)\);\s*minor\s*=\s*uint16\((\d+)\);\s*patch\s*=\s*uint16\((\d+)\);", src)
    d = re.search(r"'date',\s*\"(\d{4}-\d{2}-\d{2})\"", src)
    g = re.search(r"'model',\s*\"([^\"]+)\"", src)
    if not (m and d and g):
        sys.exit("buildFunctionList: cannot read major/minor/patch, date and model from toolboxVersion.m")
    return "%s.%s.%s" % m.groups(), d.group(1), g.group(1)


def render():
    version, date, model = read_version()
    rows = list(csv.DictReader(open(CSV, encoding="utf-8")))
    parts = ["<!DOCTYPE html><html><head><meta charset='utf-8'><title>Function Reference</title>",
             "<style>", STYLE, "</style></head><body><h1>Function Reference</h1>",
             "<p>Generated from <code>doc/functionlist.csv</code> (the single authority for the catalogue) by "
             "<code>tools/buildFunctionList.py</code>.</p><table><tr><th>package</th><th>name</th><th>kind</th>"
             "<th>level</th><th>WP</th><th>status</th><th>purpose</th></tr>"]
    for r in rows:
        parts.append("<tr><td>%s</td><td><code>%s</code></td><td>%s</td><td>%s</td><td>%s</td><td>%s</td><td>%s</td></tr>" % tuple(
            html.escape(r[k], quote=False) for k in ("package", "name", "kind", "level", "wp", "status", "h1")))
    parts.append("</table><hr><p><small>NonGravForces %s &middot; %s &middot; generated by %s</small></p></body></html>\n"
                 % (version, date, html.escape(model, quote=False)))
    return "".join(parts)


def main(argv):
    page = render()
    if "--check" in argv:
        current = open(OUT, encoding="utf-8").read() if os.path.isfile(OUT) else ""
        if current != page:
            print("buildFunctionList: doc/html/FunctionList.html is stale -> run python tools/buildFunctionList.py")
            return 1
        print("buildFunctionList: FunctionList.html is current")
        return 0
    open(OUT, "w", encoding="utf-8", newline="\n").write(page)
    print("buildFunctionList: wrote %s" % os.path.relpath(OUT, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
