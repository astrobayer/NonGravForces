%% Tutorial 10 - Several days, one scale; does the scale vary?
% One arc pins a bias well and a scale poorly: the scale is set by the spread of the modelled signal,
% and a day of drag carries only so much of it. An accelerometer's scale is a property of the
% instrument, so the natural estimate is ONE scale over many days, with a bias of its own for each
% day. This tutorial calibrates a campaign that way - on the three committed 30-minute days of
% GRACE-C and on a synthetic campaign whose truth is known - and then asks the questions that come
% after: which bias model the data support (blocked cross-validation), whether the scale differs
% from one orbital revolution to the next and what drives it, and whether a time-varying scale is
% significant.
%
% *What you will learn*
%
% * how an Arc ARRAY turns |app.calibrate| and |app.fitCalibration| into a campaign: one common
%   scale, per-day biases, a bootstrap over days;
% * what 'ScaleMode' "perArc" gives instead, and why the common scale is the better estimate;
% * how |app.compareCalibrations| ranks candidate bias models by blocked cross-validation, and why
%   AIC/BIC are reported but marked unreliable;
% * how |app.perRevolution| fits one scale per revolution and |app.attributeRevolutions| regresses
%   them on drivers, drawn by |app.plotAttribution|;
% * how a time-varying scale ('ScaleBasis') is fitted and tested with |Calibration.drift|.
%
% *Requirements:* none - the real days are the committed excerpts in |data/samples/multiday|; the
% rest is generated by |app.syntheticPair|. Run time: two to three minutes.
%
% Requirements: none
%
% NonGravForces v0.20 | 12-Nov-2026 | Claude Opus 5.5

%% Step 1 - Three real days as an Arc array
% |data/samples/multiday| holds 30 minutes of ACT1B, GNV1B and SCA1B for each of 2020-01-01, -02
% and -03 (GRACE-C). Each day's ACT1B becomes one |timeSeriesPreparation.Arc| (three columns in
% m/s2, epochs in int64 GPS ns) and the three are put in a 1x3 array, in time order. The orbits
% go into a 1x3 struct array (.epoch, .r, .v in the GCRS), and the three days' SCA1B quaternions
% into ONE attitude provider, which the Model and |calibrate| evaluate at any epoch of the three.
root = fileparts(which('setupNonGravForces'));
f = @(varargin) fullfile(root, 'data', varargin{:});
eop = referenceSystem.readEop(f('eop', 'finals2000A_2019-09_2020-03.all'));
sw = NonGravForces.io.spaceWeather(f('spaceweather', 'SW-All_2019-09_2020-03.csv'));
names = {'lin_accl_x', 'lin_accl_y', 'lin_accl_z'};
units = struct('lin_accl_x', 'm/s2', 'lin_accl_y', 'm/s2', 'lin_accl_z', 'm/s2');
accs = timeSeriesPreparation.Arc.empty;
orbs = struct('epoch', {}, 'r', {}, 'v', {});
dayS = []; secS = []; qS = [];
for d = 1:3
    day = sprintf('2020-01-%02d', d);
    [ep, r, v] = NonGravForces.io.readGNV1B(f('samples', 'multiday', "GNV1B_" + day + "_C_04.txt"), 'Eop', eop);
    orbs(d) = struct('epoch', ep, 'r', r, 'v', v);
    [e, q] = NonGravForces.io.readSCA1B(f('samples', 'multiday', "SCA1B_" + day + "_C_04.txt"));
    dayS = [dayS; e.day(:)]; secS = [secS; e.sec(:)]; qS = [qS, q]; %#ok<AGROW>
    [epC, a] = NonGravForces.io.readACC1B(f('samples', 'multiday', "ACT1B_" + day + "_C_04.txt"));
    aux = struct("obsNames", {names}, "variableNames", {names}, "variableFieldNames", {names}, ...
        "variableUnits", units, "fileName", "ACT1B_" + day + "_C_04.txt", "product", "ACT1B");
    accs(d) = timeSeriesPreparation.Arc(referenceSystem.epochTo(epC, "gpsNanoseconds"), a.', aux);
    fprintf('%s: ACT1B %d epochs, GNV1B %d, SCA1B %d\n', day, numel(accs(d).t), numel(ep.sec), size(q, 2));
end
att = NonGravForces.geom.AttitudeProvider(referenceSystem.daySecondToEpoch([dayS, secS], "GPS"), qS);

%% Step 2 - One common scale, a bias per day
% With an Arc array |app.calibrate| runs the instrument stages day by day (a day the stages refuse
% keeps its error and the campaign continues), builds each day's reference from the Model along
% that day's orbit, and fits the days JOINTLY: per axis one lsqvce system in which the scale is a
% COMMON parameter and each day's bias a local block, eliminated before the solve. The result
% carries one Calibration per day in |res.calibration| (a cell; every element holds the same
% scale and its own bias), |res.used| and |res.summary|. The a priori is the standard preset with
% its observed density scale (Swarm covers all three days). The bootstrap is over DAYS, which is
% meaningless for three of them, so it is switched off here ('NBoot' 0) and the scale sigma is the
% formal one; Step 3 shows the day bootstrap where there are days enough.
cls = NonGravForces.io.spaceWeather(f('spaceweather', 'radio_flux_adjusted_observation_2007-09_2008-03_2019-09_2020-03.txt'));
swarm = string(f('samples', 'swarm', "SW_OPER_DNS" + ["A" "B" "C"] + "POD_2_2020-01-01_2020-01-03.csv"));
S = NonGravForces.env.densityScale(swarm, sw, 'Fallback', NonGravForces.env.densityDriverScale(sw, cls));
M = NonGravForces.Model(NonGravForces.geom.graceFO("C"), NonGravForces.Options("standard"), 'Attitude', att, ...
    'Eop', eop, 'SpaceWeather', sw, 'DensityScale', S);
res = NonGravForces.app.calibrate(accs, M, 'Orbit', orbs, 'Attitude', att, 'Fit', {'NBoot', 0});
disp(res.summary(:, {'day', 'status'}))
c1 = res.calibration{1};
fprintf('common scale: S_xx %.4f +- %.4f, S_zz %.4f +- %.4f (formal), S_yy held at %.1f\n', c1.scale(1, 1), ...
    c1.uncertainty.sigmaScaleFormal(1, 1), c1.scale(3, 3), c1.uncertainty.sigmaScaleFormal(3, 3), c1.scale(2, 2));
fprintf('%-12s %14s %14s %14s %14s\n', 'day', 'b_x [m/s^2]', 'b_z [m/s^2]', 'rms x', 'rms z');
for k = find(res.used)
    j = nnz(res.used(1:k));
    rr = res.fit.residual{j}.obs;
    rmsAx = sqrt(mean(rr(all(isfinite(rr(:, [1 3])), 2), [1 3]) .^ 2, 1));
    fprintf('2020-01-%02d   %14.4e %14.4e %14.3e %14.3e\n', k, res.calibration{k}.bias.coef(1, 1), ...
        res.calibration{k}.bias.coef(3, 1), rmsAx);
end

%% Step 3 - The day bootstrap, on a synthetic campaign of ten days
% Ten consecutive synthetic "days" (0.1 day of data each, one per calendar day) share one planted
% scale and carry each its own constant bias. |app.fitCalibration| with a 1x10 Arc array solves
% the common scale and ten biases; 'NBoot' > 0 now draws DAYS with replacement - days are
% independent where the samples of one day are not - and refits each replicate from the stored
% per-day normal equations, so a replicate costs almost nothing. 'ScaleMode' "perArc" instead fits
% the ten days independently: ten scales, each from a tenth of the data. Their scatter shows what
% the common fit buys.
obs = timeSeriesPreparation.Arc.empty; ref = obs; b0 = zeros(3, 10);
for k = 1:10
    st = int64(7305 * 86400 - 43200 + 18 + (k - 1) * 86400) * int64(1e9);
    b0(:, k) = [2e-7; -1e-7; 5e-8] + 1e-8 * k * [1; -2; 3];
    [obs(k), ref(k), tr] = NonGravForces.app.syntheticPair('Days', 0.1, 'Start', st, 'Seed', k, 'Bias', b0(:, k), ...
        'BiasDrift', zeros(3, 1), 'Spikes', 0);
end
[calC, infoC] = NonGravForces.app.fitCalibration(obs, ref, 'BiasBasis', "constant", 'NBoot', 50, 'Seed', 1);
fprintf('mode %s over %d days, bootstrap over %s\n', infoC.mode, calC(1).uncertainty.nArcs, calC(1).uncertainty.bootstrap);
fprintf('common  S_xx %.5f +- %.5f (truth %.5f), S_zz %.5f +- %.5f (truth %.5f)\n', calC(1).scale(1, 1), ...
    calC(1).uncertainty.sigmaScaleBootstrap(1, 1), tr.scale(1, 1), calC(1).scale(3, 3), ...
    calC(1).uncertainty.sigmaScaleBootstrap(3, 3), tr.scale(3, 3));
bx = arrayfun(@(c) c.bias.coef(1, 1), calC);
fprintf('per-day x bias, estimate minus planted: largest %.2e m/s^2\n', max(abs(bx - b0(1, :))));
calP = NonGravForces.app.fitCalibration(obs, ref, 'BiasBasis', "constant", 'ScaleMode', "perArc", 'NBoot', 0);
sxx = arrayfun(@(c) c.scale(1, 1), calP);
fprintf('perArc  S_xx over the ten days: mean %.5f, spread (std) %.5f, range %.5f .. %.5f\n', mean(sxx), std(sxx), min(sxx), max(sxx));
figure
plot(1:10, sxx, 'o', [1 10], calC(1).scale(1, 1) * [1 1], '-', [1 10], tr.scale(1, 1) * [1 1], '--'), grid on
xlabel('day'), ylabel('S_{xx}'), legend(["perArc" "common" "planted"], 'Location', 'best')
title('one scale per day against one scale for all days')

%% Step 4 - Which bias model? Blocked cross-validation
% A richer bias model always fits better, so the residual cannot choose between models.
% |app.compareCalibrations(obs, ref, specs)| cuts the arc into contiguous blocks ('Folds', default
% 5), fits each candidate on the rest with a buffer of at least the CRN span on either side, and
% predicts the held-out block: the mean squared prediction error per axis (|cvMse|) ranks the
% candidates, and |T.Properties.UserData.best| names the winner per axis. AIC and BIC are listed
% too, flagged IC_unreliable: they count correlated filtered samples as independent and favour the
% most flexible model. The synthetic default bias drifts linearly on x and z and is constant on y.
[o1, r1] = NonGravForces.app.syntheticPair('Days', 0.25, 'Seed', 11);
specs = {{'BiasBasis', "constant"}, {'BiasBasis', "linear"}, {'BiasBasis', "pspline", 'BiasKnotSpacing_s', 5400}};
T = NonGravForces.app.compareCalibrations(o1, r1, specs, 'Names', ["const" "linear" "spline"]);
disp(T(:, {'name', 'cvMse', 'rank', 'nParams'}))
fprintf('best by CV per axis: %s (planted: linear / constant / linear)\n', strjoin(T.Properties.UserData.best, ' / '));
[~, ka] = min(T.aic);
fprintf('lowest AIC per axis: %s\n', strjoin(T.name(ka)', ' / '));

%% Step 5 - One scale per revolution
% |app.perRevolution(obs, ref)| cuts the arc into windows of one orbital period ('Period_s',
% default 5640 s) and fits a bias and a diagonal scale in each; a window with too few usable rows
% is gated and reported as NaN with its reason (|T.gate|), never as a number. The synthetic pair
% here spans two days and its along-track scale DRIFTS by 0.02 per day, so the per-revolution
% S_xx should climb. 'NBoot' 0 gives formal sigmas, which is enough to see the trend.
D = zeros(3); D(1, 1) = 0.02;
[o2, r2] = NonGravForces.app.syntheticPair('Days', 2, 'ScaleDrift', D, 'Seed', 4);
Trev = NonGravForces.app.perRevolution(o2, r2, 'NBoot', 0);
pass = Trev.gate(:, 1) == "pass";
fprintf('%d windows, %d pass on x; first passing S_xx %.4f, last %.4f\n', height(Trev), nnz(pass), ...
    Trev.scale(find(pass, 1), 1), Trev.scale(find(pass, 1, 'last'), 1));
fprintf('gate reasons: %s\n', strjoin(unique(Trev.gate(:, 1))', ', '));

%% Step 6 - Attribute the per-revolution scales to drivers
% |app.attributeRevolutions(T)| regresses the per-revolution scales on what could move them, each
% driver belonging to a FAMILY: time (the sensor), the solar flux and Ap ("density", with
% 'SpaceWeather'), beta' and the eclipse fraction ("geometry", with 'Orbit'), effect amplitudes,
% and any caller's drivers. The verdict names the family of the drivers that are significant at 3
% bootstrap sigma, "mixed" for several, "unresolved" for none or for collinear drivers. Without
% 'Orbit' or 'SpaceWeather' only time is offered, which is the right question for a drift. It
% needs at least 20 revolutions for its automatic block length. |app.plotAttribution| opens its
% own figure: the per-revolution scales against time and the strongest drivers, with the verdict
% in the title.
[A, ainfo] = NonGravForces.app.attributeRevolutions(Trev, 'NBoot', 200);
disp(A)
fprintf('drivers offered: %s\n', strjoin(string(ainfo.drivers.Properties.VariableNames), ', '));
figA = NonGravForces.app.plotAttribution(Trev, A, ainfo);
fprintf('figure "%s"\n', figA.Name);

%% Step 7 - A time-varying scale and its drift test
% Instead of windows, the scale can be one curve: with 'ScaleBasis' "linear" (or "hat",
% "pspline" with 'ScaleKnotSpacing_s') every estimated entry becomes S_ij(t) on that basis, and the
% Calibration carries the curve (|scaleCurve|), its pointwise sigma (|scaleSigmaAt|) and a Wald
% test of constancy (|drift|, |isDriftSignificant|). The test needs the BOOTSTRAP covariance: on
% the formal white-noise one it warns, because that covariance is an order of magnitude too
% small for a filtered residual. Here half a day with a planted drift of 0.01 per day on S_xx and
% none on S_zz.
D = zeros(3); D(1, 1) = 0.01;
[o3, r3, tr3] = NonGravForces.app.syntheticPair('Days', 0.5, 'Seed', 4, 'ScaleDrift', D);
calV = NonGravForces.app.fitCalibration(o3, r3, 'ScaleBasis', "linear", 'NBoot', 20, 'Seed', 1);
g = calV.scaleCurve.coef(1, 2); sg = sqrt(calV.scaleCurve.cov{1}(2, 2));
fprintf('S_xx slope %.4f +- %.4f per day (planted %.4f)\n', g, sg, tr3.scaleDrift_per_day(1, 1));
dr = calV.drift();
fprintf('drift test: p(S_xx) = %.3g, p(S_zz) = %.3g, significant at 5 %%: S_xx %d, S_zz %d\n', ...
    dr.pValue(1, 1), dr.pValue(3, 3), dr.significant(1, 1), dr.significant(3, 3));
figV = NonGravForces.app.plotCalibration(calV, o3.t);
fprintf('figure "%s": the S_xx panel shows the curve and its band\n', figV.Name);
